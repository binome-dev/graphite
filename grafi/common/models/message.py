import time
from typing import TYPE_CHECKING
from typing import Any
from typing import Dict
from typing import List
from typing import Optional
from typing import Union

from openai.types.chat.chat_completion_audio import ChatCompletionAudio
from openai.types.chat.chat_completion_message import Annotation
from openai.types.chat.chat_completion_message import FunctionCall
from openai.types.chat.chat_completion_message_tool_call import (
    ChatCompletionMessageToolCall,
)
from openai.types.chat.chat_completion_role import ChatCompletionRole
from openai.types.chat.chat_completion_tool_param import ChatCompletionToolParam
from pydantic import BaseModel
from pydantic import Field

from grafi.common.models.default_id import default_id

# Message class is based on the ChatCompletionMessage from OpenAI, extended to include all the different type of input


class Message(BaseModel):
    name: Optional[str] = None
    message_id: str = default_id
    timestamp: int = Field(default_factory=time.time_ns)
    content: Union[
        str,
        Dict[str, Any],
        List[Dict[str, Any]],
        BaseModel,
        List[BaseModel],
        None,
    ] = None
    refusal: Optional[str] = None
    """The refusal message generated by the model."""

    annotations: Optional[List[Annotation]] = None
    """
    Annotations for the message, when applicable, as when using the
    [web search tool](https://platform.openai.com/docs/guides/tools-web-search?api-mode=chat).
    """

    audio: Optional[ChatCompletionAudio] = None
    """
    If the audio output modality is requested, this object contains data about the
    audio response from the model.
    [Learn more](https://platform.openai.com/docs/guides/audio).
    """
    role: ChatCompletionRole
    tool_call_id: Optional[str] = None
    tools: Optional[List[ChatCompletionToolParam]] = None
    function_call: Optional[FunctionCall] = None
    """Deprecated and replaced by `tool_calls`.

    The name and arguments of a function that should be called, as generated by the
    model.
    """

    tool_calls: Optional[List[ChatCompletionMessageToolCall]] = None
    """The tool calls generated by the model, such as function calls."""

    if not TYPE_CHECKING:  # Type checkers keep pydantic's typed signature.

        def __init__(self, /, **data: Any) -> None:
            # Stored messages may hold it, and load: only code is told.
            if "is_streaming" in data:
                raise TypeError(
                    "Message.is_streaming was removed: a tool returns whole "
                    "messages, and streams their text with "
                    "grafi.runtime.deltas.emit_delta()."
                )
            super().__init__(**data)

        # Validation does not call it, as pydantic's RootModel marks its own.
        __init__.__pydantic_base_init__ = True


Messages = List[Message]


def tool_messages(output: Any) -> Messages:
    """A tool's output, which must be its messages.

    Raises:
        TypeError: If it is not a list of messages.
    """
    if isinstance(output, list) and all(isinstance(m, Message) for m in output):
        return output
    got = type(output).__name__
    if isinstance(output, list):
        got = f"a list holding {type(next(m for m in output if not isinstance(m, Message))).__name__}"
    raise TypeError(
        f"A tool returns its output as a list of messages, not {got}: return "
        "[message] for one, [] for none."
    )
